using System;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace MarketShopandRetailSystem.Multiplayer.EditorTools
{
    /// <summary>
    /// Keys for the LAN licence (see LanLicence). One ECDSA P-256 key pair lives in the user environment variable
    /// SHOPSIM_LICENCE_KEY as base64(X || Y || D), 96 bytes. Both halves are written to git-ignored files:
    ///
    ///   • the whole key into the IntegrityModule as LicenceKey.Generated.cs (Editor-only Cloud assembly, so it never
    ///     ships in a player), on Editor load; the module signs licences with it. Redeploy the module after a change.
    ///   • the public half into native/shopsim_core/shopsim_core_licence_key.h, before every native core build
    ///     (NativeCoreBuildStep); the core verifies licences with it.
    ///
    /// Without the variable both files are removed and every licence check fails (-2), which only matters to a release
    /// player: the Editor and development builds don't enforce licences. Keep the key stable and backed up: a new key
    /// makes every issued licence invalid until players next go online, and needs a native rebuild and a redeploy.
    /// Create one with PowerShell 7 (Unity's Mono can't generate EC keys):
    ///   $e=[Security.Cryptography.ECDsa]::Create([Security.Cryptography.ECCurve+NamedCurves]::nistP256); $p=$e.ExportParameters($true)
    ///   [Environment]::SetEnvironmentVariable('SHOPSIM_LICENCE_KEY',[Convert]::ToBase64String([byte[]]($p.Q.X+$p.Q.Y+$p.D)),'User')
    /// </summary>
    public static class LanLicenceKeys
    {
        /// <summary>Name of the environment variable holding the licence key (from <see cref="HardeningSettings"/>).</summary>
        public static string KeyVar => HardeningSettings.Current.licenceKeyVar;
        private const string ModuleKeyFile = "LicenceKey.Generated.cs";
        private const string DefaultModuleDir = "Assets/CloudCode/IntegrityModule/Cloud";

        public static string NativeHeaderPath => HardeningSettings.Current.NativeSourcePath("shopsim_core_licence_key.h");

        /// <summary>The 96-byte key, or null when the variable is missing or malformed.</summary>
        public static byte[] Key()
        {
            string value = Environment.GetEnvironmentVariable(KeyVar);
            if (string.IsNullOrWhiteSpace(value) && Application.platform == RuntimePlatform.WindowsEditor)
            {
                value = Environment.GetEnvironmentVariable(KeyVar, EnvironmentVariableTarget.User);
            }
            if (string.IsNullOrWhiteSpace(value)) return null;
            try
            {
                byte[] key = Convert.FromBase64String(value.Trim());
                if (key.Length == 96) return key;
            }
            catch (FormatException) { }
            Debug.LogWarning("[LanLicence] " + KeyVar + " is not a base64 96-byte P-256 key (X||Y||D); ignoring it.");
            return null;
        }

        [InitializeOnLoadMethod]
        private static void OnLoad()
        {
            // Importing from InitializeOnLoad would recompile mid-reload; write now, import once it has finished.
            EnsureModuleKey(deferImport: true);
        }

        /// <summary>Brings the module's LicenceKey.Generated.cs in line with the key. True when it changed.</summary>
        public static bool EnsureModuleKey(bool deferImport = false)
        {
            string dir = ModuleDir();
            if (dir == null) return false;
            string path = Path.Combine(dir, ModuleKeyFile);
            byte[] key = Key();
            string desired = null;
            if (key != null)
            {
                var settings = IntegrityUploadSettings.Find();
                string ns = settings != null ? settings.moduleNamespace : "IntegrityModule.Cloud";
                var sb = new StringBuilder();
                sb.AppendLine("// <auto-generated>");
                sb.AppendLine("// ECDSA P-256 key the IntegrityModule signs LAN licences with, from " + KeyVar + ". Git-ignored: never commit it.");
                sb.AppendLine("// Generated by LanLicenceKeys.");
                sb.AppendLine("// </auto-generated>");
                sb.AppendLine($"namespace {ns}");
                sb.AppendLine("{");
                sb.AppendLine("    public static partial class LicenceKey");
                sb.AppendLine("    {");
                sb.AppendLine($"        static partial void Load(ref string key) => key = \"{Convert.ToBase64String(key)}\";");
                sb.AppendLine("    }");
                sb.AppendLine("}");
                desired = sb.ToString();
            }
            string current = File.Exists(path) ? File.ReadAllText(path) : null;
            if (desired == current) return false;

            string rel = Path.GetRelativePath(Path.GetDirectoryName(Application.dataPath), path).Replace('\\', '/');
            if (desired == null)
            {
                File.Delete(path);
                if (File.Exists(path + ".meta")) File.Delete(path + ".meta");
                Debug.Log("[LanLicence] No " + KeyVar + "; removed the module's licence key.");
            }
            else
            {
                File.WriteAllText(path, desired);
                Debug.Log("[LanLicence] Licence signing key written to the IntegrityModule. Redeploy it to publish.");
            }
            if (deferImport) EditorApplication.delayCall += () => AssetDatabase.ImportAsset(rel);
            else AssetDatabase.ImportAsset(rel);
            return true;
        }

        /// <summary>
        /// Brings native/shopsim_core/shopsim_core_licence_key.h in line with the key's public half (deleted without a
        /// key). Called before every native core build. True when it changed.
        /// </summary>
        public static bool EnsureNativeHeader()
        {
            byte[] key = Key();
            string desired = null;
            if (key != null)
            {
                var sb = new StringBuilder();
                sb.Append("// Generated by LanLicenceKeys from ").Append(KeyVar).Append(" (public half). Git-ignored: never commit.\n");
                sb.Append("#define SSC_LICENCE_PUBKEY_BYTES ");
                for (int i = 0; i < 64; i++)
                {
                    if (i > 0) sb.Append(", ");
                    sb.Append("0x").Append(key[i].ToString("x2"));
                }
                sb.Append('\n');
                desired = sb.ToString();
            }
            string current = File.Exists(NativeHeaderPath) ? File.ReadAllText(NativeHeaderPath) : null;
            if (desired == current) return false;
            if (desired == null) File.Delete(NativeHeaderPath);
            else File.WriteAllText(NativeHeaderPath, desired);
            return true;
        }

        private static string ModuleDir()
        {
            var settings = IntegrityUploadSettings.Find();
            string projectRoot = Path.GetDirectoryName(Application.dataPath);
            string dir = settings != null
                ? Path.GetDirectoryName(Path.Combine(projectRoot, settings.moduleExpectedDigestsFile))
                : Path.Combine(projectRoot, DefaultModuleDir);
            return dir != null && Directory.Exists(dir) ? dir : null;
        }
    }
}
