using System.IO;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEngine;

namespace MarketShopandRetailSystem.Multiplayer.EditorTools
{
    /// <summary>
    /// Keeps a tiny generated source in the game's runtime assembly in sync with the <see cref="HardeningSettings"/>
    /// asset, so the runtime <c>HardeningRuntimeConfig</c> carries the same binary names and in-player subpaths the
    /// build steps use. The runtime can't read the Editor-only settings asset, so this is how the asset stays the
    /// single source of truth for both sides. Regenerated whenever the Editor loads (a settings change recompiles and
    /// reruns this) and ensured before every player build. The file is git-ignored and regenerates on demand; without
    /// it the runtime simply uses its built-in defaults, which equal the asset's defaults.
    /// </summary>
    public class HardeningRuntimeConfigBuildStep : IPreprocessBuildWithReport
    {
        public int callbackOrder => 90;

        static HardeningRuntimeConfigBuildStep()
        {
            EditorApplication.delayCall += () => EnsureGenerated();
        }

        public void OnPreprocessBuild(BuildReport report) => EnsureGenerated();

        private static string Path_ => HardeningSettings.Current.runtimeConfigGeneratedPath;

        /// <summary>Brings the generated registration in line with the settings asset. True when it changed.</summary>
        public static bool EnsureGenerated()
        {
            HardeningSettings cfg = HardeningSettings.Current;
            string desired = Source(cfg);
            string path = Path_;
            string current = File.Exists(path) ? File.ReadAllText(path) : null;
            if (desired == current) return false;

            string dir = System.IO.Path.GetDirectoryName(path);
            if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
            File.WriteAllText(path, desired);
            AssetDatabase.ImportAsset(path);
            Debug.Log("[Hardening] Runtime config registration generated from HardeningSettings.");
            return true;
        }

        private static string Source(HardeningSettings cfg)
        {
            string Q(string s) => "\"" + (s ?? "").Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
            return
"// <auto-generated> Generated from the HardeningSettings asset by HardeningRuntimeConfigBuildStep. Do not edit. </auto-generated>\n" +
"using UnityEngine;\n" +
"\n" +
"namespace MarketShopandRetailSystem.Multiplayer\n" +
"{\n" +
"    internal static class HardeningRuntimeConfigRegistration\n" +
"    {\n" +
"        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.BeforeSceneLoad)]\n" +
"        private static void Register()\n" +
"        {\n" +
"            HardeningRuntimeConfig.Current = new HardeningRuntimeConfig\n" +
"            {\n" +
"                gameAssemblyName = " + Q(cfg.gameAssemblyName) + ",\n" +
"                nativeCoreName = " + Q(cfg.nativeCoreName) + ",\n" +
"                il2cppMetadataName = " + Q(cfg.il2cppMetadataName) + ",\n" +
"                nativePluginSubpath = " + Q(cfg.nativePluginSubpath) + ",\n" +
"                il2cppMetadataSubpath = " + Q(cfg.il2cppMetadataSubpath) + ",\n" +
"            };\n" +
"        }\n" +
"    }\n" +
"}\n";
        }
    }
}
